"""Compile-time benchmarks of the mtl typelist algorithms.

Generates a header with N types (type_0, type_1, ...) and a list of them,
one translation unit per operation that instantiates the operation
INSTANCES times (each instance on a list of its own, so nothing is
memoized away), compiles every unit with every mtl include directory given
and reports per unit:

  cpu   best of --repeat runs, user+system seconds of the compiler
  rss   peak resident set in MB
  ggc   GCC's total garbage-collected allocation in MB (-ftime-report):
        deterministic, the figure to compare when the machine is noisy

Examples (from the repository root):

  benchmarks/typelist_compile_time.py                  # the checked-out mtl
  benchmarks/typelist_compile_time.py --mtl main=../mtl-main/include --mtl work=include
  benchmarks/typelist_compile_time.py --ops filter,unique --sizes 100,400 --instances 10
  benchmarks/typelist_compile_time.py --cxx arm-zephyr-eabi-g++
"""

import argparse
import os
import re
import resource
import shutil
import subprocess
import sys
import time

REPOSITORY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# One line per operation, instantiated per I on `list_t<I>` - the N types
# behind a distinct head, so every instance is a fresh instantiation - with
# `pred<I>::type`, a predicate selecting every (I + 2)th type, and
# `pred<N>::type`, one matching nothing (a full walk). `use(x)` and
# `use_t<T>()` consume the result.
OPERATIONS = {
    'has_a': 'use(mtl::has_a_v<list_t<I>, type_last>);',
    'count_if': 'use(mtl::count_if_v<list_t<I>, pred<I>::template type>);',
    'all_of': 'use(mtl::all_of_v<list_t<I>, pred<I>::template type>);',
    'any_of': 'use(mtl::any_of_v<list_t<I>, pred<N>::template type>);',
    'none_of': 'use(mtl::none_of_v<list_t<I>, pred<N>::template type>);',
    'find_if': 'use_t<mtl::find_if_t<list_t<I>, pred<N>::template type>>();',
    'filter': 'use_t<mtl::filter_t<list_t<I>, pred<I>::template type>>();',
    'remove_if': 'use_t<mtl::remove_if_t<list_t<I>, pred<I>::template type>>();',
    'transform': 'use_t<mtl::transform_t<list_t<I>, std::add_const>>();',
    'unique': 'use_t<mtl::unique_t<mtl::concat_t<list_t<I>, list_t<I>>>>();',
    'reverse': 'use_t<mtl::reverse_t<list_t<I>>>();',
    'index_of': 'use(mtl::index_of_v<type_last, list_t<I>>);',
    'at': 'use_t<mtl::at_t<N, list_t<I>>>();',
    'back': 'use_t<mtl::back_t<list_t<I>>>();',
    'linearize': 'use_t<mtl::linearize_t<mtl::typelist<list_t<I>, list_t<I>>>>();',
    'concat_2': 'use_t<mtl::concat_t<list_t<I>, list>>();',
    'concat_3': 'use_t<mtl::concat_t<list_t<I>, list, list>>();',
    'concat_5': 'use_t<mtl::concat_t<list_t<I>, list, list, list, list>>();',
    'sort': 'use_t<mtl::sort_t<list_t<I>, mtl::internal::gt_value>>();',
}

# Recursion-depth bound operations keep their lists short
SIZE_CAP = {'sort': 64}

HEADER = '''// generated by benchmarks/typelist_compile_time.py - N={size}
#pragma once
#include <mtl/Typelist.hpp>
#include <mtl/TypelistAlgorithms.hpp>
#include <type_traits>

constexpr std::size_t N = {size};

{types}

using type_last = type_{last};

using list = mtl::typelist<{elements}>;

template<std::size_t I>
struct head {{
    static constexpr std::size_t value = N + I;
}};

template<std::size_t I>
using list_t = mtl::prepend_t<head<I>, list>;

template<std::size_t I>
struct pred {{
    template<typename T>
    struct type : std::bool_constant<(T::value % (I + 2)) == 0> {{}};
}};

template<>
struct pred<N> {{
    template<typename T>
    struct type : std::false_type {{}};
}};

template<typename T>
void use_t() {{}}

inline void use(auto) {{}}
'''

UNIT = '''// generated by benchmarks/typelist_compile_time.py - {operation}, N={size}, {instances} instances
#include "types_{size}.hpp"

template<std::size_t I>
void instance()
{{
    {line}
}}

void run()
{{
{calls}
}}
'''


def compile_once(command):
    process = subprocess.Popen(command, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)
    stderr = process.stderr.read()
    _, status, usage = os.wait4(process.pid, 0)
    process.returncode = status
    if status != 0:
        error = next((line for line in stderr.splitlines() if 'error:' in line), stderr[:200])
        print(f'{" ".join(command)}\n  {error}', file=sys.stderr)
        return None
    ggc = re.search(r'TOTAL\s*:\s*[\d.]+\s+(\d+)M', stderr)
    return usage.ru_utime + usage.ru_stime, usage.ru_maxrss / 1024, int(ggc.group(1)) if ggc else None


def measure(cxx, include, unit, std, repeat):
    """The best of `repeat` compilations, or None when the unit does not compile."""
    command = [cxx, f'-std={std}', '-ftime-report', '-I', include, '-fsyntax-only', unit]
    best = None
    for _ in range(repeat):
        run = compile_once(command)
        if run is None:
            return None
        if best is None or run[0] < best[0]:
            best = run
    return best


def parse_include(argument):
    label, separator, path = argument.rpartition('=')
    path = os.path.abspath(path)
    return (label if separator else os.path.relpath(path)), path


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--mtl', action='append', metavar='[LABEL=]DIR',
                        help='an mtl include directory to measure (repeatable; default: this repository)')
    parser.add_argument('--cxx', default=os.environ.get('CXX', 'c++'))
    parser.add_argument('--std', default='c++20')
    parser.add_argument('--ops', help='comma-separated subset of the operations (default: all)')
    parser.add_argument('--sizes', default='37,150,600',
                        help='list sizes N (comma-separated; the defaults are no powers of two on purpose)')
    parser.add_argument('--instances', type=int, default=16, help='instantiations per unit')
    parser.add_argument('--repeat', type=int, default=3, help='runs per unit, the best counts')
    parser.add_argument('--out', default=os.path.join(REPOSITORY, 'build', 'benchmarks'))
    arguments = parser.parse_args()

    includes = ([parse_include(m) for m in arguments.mtl] if arguments.mtl
                else [('mtl', os.path.join(REPOSITORY, 'include'))])
    sizes = [int(s) for s in arguments.sizes.split(',')]
    operations = arguments.ops.split(',') if arguments.ops else list(OPERATIONS)
    unknown = set(operations) - set(OPERATIONS)
    if unknown:
        sys.exit(f'unknown operations: {", ".join(sorted(unknown))}')

    shutil.rmtree(arguments.out, ignore_errors=True)
    os.makedirs(arguments.out)
    for size in {min(size, SIZE_CAP.get(op, size)) for op in operations for size in sizes}:
        types = '\n'.join(f'struct type_{i} {{ static constexpr std::size_t value = {i}; }};' for i in range(size))
        elements = ', '.join(f'type_{i}' for i in range(size))
        with open(os.path.join(arguments.out, f'types_{size}.hpp'), 'w') as header:
            header.write(HEADER.format(size=size, last=size - 1, types=types, elements=elements))
    units = []
    for operation in operations:
        for size in sorted({min(size, SIZE_CAP.get(operation, size)) for size in sizes}):
            path = os.path.join(arguments.out, f'{operation}_{size}.cpp')
            calls = '\n'.join(f'    instance<{i}>();' for i in range(arguments.instances))
            with open(path, 'w') as unit:
                unit.write(UNIT.format(operation=operation, size=size, instances=arguments.instances,
                                       line=OPERATIONS[operation], calls=calls))
            units.append((f'{operation} {size}', path))

    width = max(len(name) for name, _ in units)
    print(f'{arguments.cxx}, -std={arguments.std}, -fsyntax-only, {arguments.instances} instances, '
          f'best of {arguments.repeat}')
    print(f'{"":{width}}  ' + '  '.join(f'{label:>26}' for label, _ in includes))
    print(f'{"":{width}}  ' + '  '.join(f'{"cpu s   rss MB   ggc MB":>26}' for _ in includes))
    for name, path in units:
        cells = []
        for _, include in includes:
            run = measure(arguments.cxx, include, path, arguments.std, arguments.repeat)
            if run is None:
                cells.append('does not compile')
                continue
            cpu, rss, ggc = run
            cells.append(f'{cpu:7.2f} {rss:8.0f} {ggc if ggc is not None else "-":>8}')
        print(f'{name:{width}}  ' + '  '.join(f'{c:>26}' for c in cells), flush=True)


if __name__ == '__main__':
    main()
